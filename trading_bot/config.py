@dataclass
class MarketBreadth:
    """Market breadth indicators."""
    timestamp: datetime
    advance_decline_ratio: float
    advance_decline_line: float
    new_highs: int
    new_lows: int
    percent_above_50ma: float
    percent_above_200ma: float
    mcclellan_oscillator: float
    breadth_thrust: float

    @property
    def breadth_score(self) -> float:
        """Calculate overall breadth score (0-100)."""
        score = 50.0

        # AD ratio contribution
        if self.advance_decline_ratio > 2:
            score += 15
        elif self.advance_decline_ratio > 1:
            score += 10
        elif self.advance_decline_ratio < 0.5:
            score -= 15
        elif self.advance_decline_ratio < 1:
            score -= 10

        # MA contribution
        score += (self.percent_above_50ma - 50) * 0.3
        score += (self.percent_above_200ma - 50) * 0.2

        return max(0, min(100, score))


