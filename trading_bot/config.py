@dataclass
class FairValueArea:
    """Fair Value Area data structure."""
    vah: float  # Value Area High
    val: float  # Value Area Low
    poc: float  # Point of Control
    developing: bool = True  # Is this a developing or settled VA

    @property
    def midpoint(self) -> float:
        """Calculate the midpoint of the value area."""
        return (self.vah + self.val) / 2

    @property
    def range(self) -> float:
        """Calculate the value area range."""
        return self.vah - self.val

    def is_price_above(self, price: float) -> bool:
        """Check if price is above the value area."""
        return price > self.vah

    def is_price_below(self, price: float) -> bool:
        """Check if price is below the value area."""
        return price < self.val

    def is_price_within(self, price: float) -> bool:
        """Check if price is within the value area."""
        return self.val <= price <= self.vah


