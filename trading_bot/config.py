def get_default_config() -> BotConfig:
    """
    Get the default bot configuration.

    Returns:
        BotConfig: Default configuration instance.
    """
    return BotConfig()


def load_config_from_env() -> BotConfig:
    """
    Load configuration from environment variables.

    Returns:
        BotConfig: Configuration with environment overrides.
    """
    config = get_default_config()

    # Override from environment
    if os.getenv('TRADING_SYMBOL'):
        config.symbol = os.getenv('TRADING_SYMBOL')

    if os.getenv('PAPER_TRADING'):
        config.paper_trading = os.getenv('PAPER_TRADING').lower() == 'true'

    if os.getenv('INITIAL_CAPITAL'):
        config.initial_capital = float(os.getenv('INITIAL_CAPITAL'))

    if os.getenv('LOG_LEVEL'):
        config.log_level = os.getenv('LOG_LEVEL')

    return config


def validate_config(config: BotConfig) -> Tuple[bool, List[str]]:
    """
    Validate the bot configuration.

    Args:
        config: Configuration to validate.

    Returns:
        Tuple of (is_valid, list of error messages).
    """
    errors = []

    # Validate risk settings
    if config.risk.max_position_size_percent <= 0:
        errors.append("max_position_size_percent must be positive")

    if config.risk.max_position_size_percent > 100:
        errors.append("max_position_size_percent cannot exceed 100%")

    if config.risk.min_risk_reward_ratio < 1:
        errors.append("min_risk_reward_ratio should be at least 1.0")

    # Validate strategy settings
    if config.strategy.min_confidence < 0 or config.strategy.min_confidence > 100:
        errors.append("min_confidence must be between 0 and 100")

    # Validate indicator settings
    if config.indicators.rsi_period < 2:
        errors.append("rsi_period must be at least 2")

    if config.indicators.rsi_overbought <= config.indicators.rsi_oversold:
        errors.append("rsi_overbought must be greater than rsi_oversold")

    return len(errors) == 0, errors


