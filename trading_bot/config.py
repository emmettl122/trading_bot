@dataclass
class TradingSignal:
    """Trading signal generated by the strategy."""
    timestamp: datetime
    symbol: str
    signal_type: SignalType
    direction: PositionSide
    entry_price: float
    stop_loss: float
    take_profit: float
    confidence: float  # 0-100
    position_size: Optional[PositionSize] = None
    rationale: str = ""
    indicators_aligned: int = 0
    total_indicators: int = 0

    @property
    def risk_reward_ratio(self) -> float:
        """Calculate the risk-reward ratio."""
        risk = abs(self.entry_price - self.stop_loss)
        reward = abs(self.take_profit - self.entry_price)
        if risk > 0:
            return reward / risk
        return 0.0

    def to_signal(self, timeframe: str) -> Optional["Signal"]:
        """
        Convert TradingSignal to standardized Signal for webhook output.

        This method transforms the internal TradingSignal format into
        the standardized Signal format suitable for TradingView webhooks
        and other external integrations.

        Args:
            timeframe: Timeframe string (e.g., "15m", "1h") from StrategyConfig.

        Returns:
            Signal instance or None if this is a NO_SIGNAL or FLAT direction.

        Example:
            >>> signal = trading_signal.to_signal("15m")
            >>> if signal:
            ...     print(signal.to_json())
        """
        # Import here to avoid circular dependency
        from signal import Signal as WebhookSignal

        # Return None for NO_SIGNAL
        if self.signal_type == SignalType.NO_SIGNAL:
            return None

        # Determine side from direction
        if self.direction == PositionSide.LONG:
            side = "LONG"
        elif self.direction == PositionSide.SHORT:
            side = "SHORT"
        else:
            return None  # FLAT direction cannot produce a Signal

        # Extract base signal type (remove _LONG/_SHORT suffix)
        signal_type_name = self.signal_type.name
        if signal_type_name.startswith("BREAKOUT"):
            base_type = "BREAKOUT"
        elif signal_type_name.startswith("REJECTION"):
            base_type = "REJECTION"
        elif signal_type_name.startswith("DIVERGENCE"):
            base_type = "DIVERGENCE"
        else:
            return None  # Unknown signal type

        # Calculate multiple targets from single take_profit
        targets = self._calculate_multi_targets()

        # Normalize confidence from 0-100 to 0.0-1.0
        normalized_confidence = min(1.0, max(0.0, self.confidence / 100.0))

        # Format timestamp as UTC ISO string
        if self.timestamp.tzinfo is None:
            # Assume UTC if no timezone info
            timestamp_str = self.timestamp.replace(tzinfo=timezone.utc).isoformat()
        else:
            timestamp_str = self.timestamp.astimezone(timezone.utc).isoformat()

        return WebhookSignal(
            symbol=self.symbol,
            timeframe=timeframe,
            side=side,
            entry_price=round(self.entry_price, 2),
            stop_loss=round(self.stop_loss, 2),
            targets=targets,
            signal_type=base_type,
            confidence=round(normalized_confidence, 4),
            timestamp=timestamp_str,
        )

    def _calculate_multi_targets(self) -> List[float]:
        """
        Calculate multiple take-profit targets from single take_profit.

        Uses a tiered approach for scaling out positions:
        - Target 1: 50% of the way to original take_profit (conservative)
        - Target 2: Original take_profit (primary target)
        - Target 3: 150% of the distance (extended/runner)

        Returns:
            List of 3 target prices, sorted appropriately for direction.
        """
        if self.direction == PositionSide.LONG:
            distance = self.take_profit - self.entry_price
            target_1 = round(self.entry_price + distance * 0.5, 2)
            target_2 = round(self.take_profit, 2)
            target_3 = round(self.entry_price + distance * 1.5, 2)
        else:  # SHORT
            distance = self.entry_price - self.take_profit
            target_1 = round(self.entry_price - distance * 0.5, 2)
            target_2 = round(self.take_profit, 2)
            target_3 = round(self.entry_price - distance * 1.5, 2)

        return [target_1, target_2, target_3]


